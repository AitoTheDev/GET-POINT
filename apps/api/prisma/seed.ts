/**
 * Idempotent seed: roles + permissions, sample Community/Locations/shops, shop categories,
 * first admin.
 * In development it also creates one Staff and one Community Manager account for testing.
 *
 *   npm run db:seed
 */
import { PASSWORD_MIN_LENGTH, SystemRole } from '@getpoint/shared';
import { PrismaClient } from '@prisma/client';
import { hashPassword } from '../src/auth/crypto.util';
import { SYSTEM_ROLES } from '../src/roles/default-permissions';

const prisma = new PrismaClient();

const SAMPLE_COMMUNITY = 'GET POINT Community';
const SAMPLE_LOCATIONS = [
  { name: 'Community Mall A', province: 'กรุงเทพมหานคร' },
  { name: 'Community Mall B', province: 'กรุงเทพมหานคร' },
  { name: 'Community Mall C', province: 'กรุงเทพมหานคร' },
];
const DEFAULT_CATEGORIES = ['คาเฟ่', 'อาหาร', 'ค้าปลีก', 'เบเกอรี่', 'บริการ'];
/** Sample shops for the first location, as in the Shops & Locations mockup. */
const SAMPLE_SHOPS = [
  { name: 'ร้านกาแฟ A', category: 'คาเฟ่', receiptName: 'CAFE A', participating: true },
  { name: 'ร้านอาหาร B', category: 'อาหาร', receiptName: 'RESTAURANT B', participating: true },
  { name: 'ร้านค้าปลีก C', category: 'ค้าปลีก', receiptName: 'RETAIL C', participating: true },
  { name: 'ร้านเบเกอรี่ D', category: 'เบเกอรี่', receiptName: 'BAKERY D', participating: true },
  { name: 'ร้านบริการ E', category: 'บริการ', receiptName: 'SERVICE E', participating: false },
];

async function seedRoles() {
  for (const role of SYSTEM_ROLES) {
    const saved = await prisma.role.upsert({
      where: { key: role.key },
      // Never overwrite permissions an admin has edited; only create them the first time.
      update: { isSystem: true },
      create: {
        key: role.key,
        name: role.name,
        description: role.description,
        isSystem: true,
        permissions: { create: role.permissions },
      },
    });
    if (role.key === SystemRole.ADMIN) {
      // Admin always keeps full access, even if rows were removed by hand.
      for (const p of role.permissions) {
        await prisma.rolePermission.upsert({
          where: { roleId_menu: { roleId: saved.id, menu: p.menu } },
          update: { canView: true, canManage: true },
          create: { ...p, roleId: saved.id },
        });
      }
    }
  }
}

// Codes (COM/LOC/S + number) are generated by the database, so records are matched by name.
async function seedOrganisation() {
  const community =
    (await prisma.community.findFirst({ where: { name: SAMPLE_COMMUNITY } })) ??
    (await prisma.community.create({ data: { name: SAMPLE_COMMUNITY } }));

  const locations = [];
  for (const loc of SAMPLE_LOCATIONS) {
    locations.push(
      (await prisma.location.findFirst({ where: { communityId: community.id, name: loc.name } })) ??
        (await prisma.location.create({ data: { ...loc, communityId: community.id } })),
    );
  }

  const categories = new Map<string, string>();
  for (const [index, name] of DEFAULT_CATEGORIES.entries()) {
    const category = await prisma.shopCategory.upsert({
      where: { name },
      update: {},
      create: { name, sortOrder: index + 1 },
    });
    categories.set(name, category.id);
  }

  // Sample shops only when the first location has none yet.
  if ((await prisma.shop.count({ where: { locationId: locations[0].id } })) === 0) {
    for (const shop of SAMPLE_SHOPS) {
      await prisma.shop.create({
        data: {
          locationId: locations[0].id,
          name: shop.name,
          categoryId: categories.get(shop.category),
          receiptName: shop.receiptName,
          participating: shop.participating,
          status: shop.participating ? 'ACTIVE' : 'INACTIVE',
        },
      });
    }
  }
  return { community, locations };
}

async function upsertUser(input: {
  email: string;
  name: string;
  password: string;
  roleKey: SystemRole;
  scopeAll: boolean;
  scope?: { communityId?: string; locationId?: string }[];
}) {
  const existing = await prisma.user.findUnique({ where: { email: input.email } });
  if (existing) return { created: false, email: input.email };

  const role = await prisma.role.findUniqueOrThrow({ where: { key: input.roleKey } });
  await prisma.user.create({
    data: {
      email: input.email,
      name: input.name,
      passwordHash: await hashPassword(input.password),
      roleId: role.id,
      scopeAll: input.scopeAll,
      scopes: { create: input.scope ?? [] },
    },
  });
  return { created: true, email: input.email };
}

async function main() {
  const adminEmail = (process.env.SEED_ADMIN_EMAIL ?? 'admin@getpoint.local').trim().toLowerCase();
  const adminPassword = process.env.SEED_ADMIN_PASSWORD ?? '';
  if (adminPassword.length < PASSWORD_MIN_LENGTH || adminPassword === 'CHANGE_ME') {
    throw new Error(
      `Set SEED_ADMIN_PASSWORD in apps/api/.env (at least ${PASSWORD_MIN_LENGTH} characters) before seeding.`,
    );
  }

  await seedRoles();
  const { community, locations } = await seedOrganisation();

  const results = [
    await upsertUser({
      email: adminEmail,
      name: 'ผู้ดูแลระบบ',
      password: adminPassword,
      roleKey: SystemRole.ADMIN,
      scopeAll: true,
    }),
  ];

  if (process.env.NODE_ENV !== 'production') {
    results.push(
      await upsertUser({
        email: 'staff@getpoint.local',
        name: 'เจ้าหน้าที่ ทดสอบ',
        password: adminPassword,
        roleKey: SystemRole.STAFF,
        scopeAll: false,
        scope: [{ locationId: locations[0].id }],
      }),
      await upsertUser({
        email: 'manager@getpoint.local',
        name: 'ผู้จัดการ ทดสอบ',
        password: adminPassword,
        roleKey: SystemRole.COMMUNITY_MANAGER,
        scopeAll: false,
        scope: [{ communityId: community.id }],
      }),
    );
  }

  console.log('Seed complete.');
  for (const r of results) {
    console.log(`  ${r.created ? 'created ' : 'exists  '} ${r.email}`);
  }
  console.log('  (passwords are not printed; new accounts use SEED_ADMIN_PASSWORD)');
}

main()
  .catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
